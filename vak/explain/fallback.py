_BANK = {"te": TE, "hi": HI}
MAX_FLAGS = 3
MAX_STEPS = 3


def build(report: Report, lang: str) -> str:
    t = _BANK[lang]
    score = report.consistency_score
    lines = [t["model"], t["what"], t["total"].format(n=report.total_perturbations)]
    lines.append(t["changed"].format(n=report.unexpected_changes) if report.unexpected_changes else t["unchanged"])
    lines.append(t["score"].format(n=round(score * 100)))

    tone = "concern" if score < CONCERN_BELOW else "steady" if score > STEADY_ABOVE else "mixed"
    lines += t[tone]

    codes = [f.code for f in report.flags]
    lines += [t["flags"][c] for c in codes[:MAX_FLAGS] if c in t["flags"]]

    leaders = [u for u in report.units if u.raw >= 0.5 and u.importance >= 0.99]
    if len(leaders) == 1 and len(report.units) >= 4:
        word = trim_punct(leaders[0].text)
        if word:
            lines.append(t["top_word"].format(w=word))

    lines.append(t["next"])
    steps = [t["steps"][c] for c in codes[:MAX_STEPS] if c in t["steps"]]
    lines += steps or [t["steps"]["default"]]
    return " ".join(lines)
